"""
PDF parser for NMIMS SAP attendance reports.

This module handles reading and extracting attendance data from
SVKM/NMIMS Student Attendance PDFs generated by the SAP system.

The PDF structure is:
    Page 1: Header with student metadata + attendance table
    Pages 2-N: Continuation of attendance table
    Last page: Footer/disclaimer

Metadata fields (Page 1 header):
    - Institution name
    - Student Name
    - Student Number
    - Roll No.
    - Academic Year & Academic Session
    - Program Name
    - Attendance Report Duration

Attendance table columns:
    Sr No. | Course Name | Date | Start Time | End Time | Attendance

Attendance statuses:
    P = Present
    A = Absent
    NU = Not Updated
    E = Exemption
    L = Late Admission
"""

import re
import fitz  # PyMuPDF
from datetime import datetime
from typing import Optional

from app.models import StudentMetadata, AttendanceRecord
from app.normalizer import normalize_course_name


# Valid attendance status codes
VALID_STATUSES = {"P", "A", "NU", "E", "L"}

# Month abbreviation to number mapping
MONTH_MAP = {
    "Jan": 1, "Feb": 2, "Mar": 3, "Apr": 4,
    "May": 5, "Jun": 6, "Jul": 7, "Aug": 8,
    "Sep": 9, "Oct": 10, "Nov": 11, "Dec": 12
}

# Date pattern: "Jul 13, 2026" or "Sep 1, 2026"
DATE_PATTERN = re.compile(
    r'(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\s+(\d{1,2}),\s+(\d{4})'
)

# Time pattern: "11:00:01 AM" or "1:00:00 PM"
TIME_PATTERN = re.compile(
    r'(\d{1,2}):(\d{2}):(\d{2})\s+(AM|PM)'
)

# Report duration pattern: "From DD.MM.YYYY to DD.MM.YYYY"
DURATION_PATTERN = re.compile(
    r'From\s+(\d{2}\.\d{2}\.\d{4})\s+to\s+(\d{2}\.\d{2}\.\d{4})'
)


def parse_attendance_pdf(pdf_bytes: bytes, filename: str = "unknown.pdf", skip_institution_check: bool = False) -> tuple[StudentMetadata, list[AttendanceRecord]]:
    """
    Parse an NMIMS attendance PDF and extract metadata + attendance records.

    Args:
        pdf_bytes: Raw PDF file content as bytes
        filename: Original filename for error messages
        skip_institution_check: When True (e.g. for portal-fetched PDFs), skip the
            institution name check and rely solely on parsed records for validation.

    Returns:
        Tuple of (StudentMetadata, list of AttendanceRecord)

    Raises:
        ValueError: If the PDF cannot be parsed or has an unsupported structure
    """
    # Detect obviously wrong file types before attempting PDF parsing
    _check_file_type(pdf_bytes, filename)

    try:
        doc = fitz.open(stream=pdf_bytes, filetype="pdf")
    except Exception as e:
        raise ValueError(
            f"Cannot open PDF file '{filename}': {str(e)}. "
            "Ensure the file is a valid, non-password-protected PDF."
        )

    if len(doc) == 0:
        raise ValueError(f"PDF file '{filename}' has no pages")

    # Extract all text from all pages
    all_text = ""
    page_texts = []
    for page in doc:
        text = page.get_text()
        page_texts.append(text)
        all_text += text + "\n"

    doc.close()

    # Run a lightweight institution check (requires only 1 indicator now).
    # For portal-fetched PDFs we skip this entirely and rely on record parsing.
    if not skip_institution_check and not _is_nmims_attendance_pdf(all_text):
        # Before giving up, try parsing records — if records exist, accept the file.
        records = _extract_records(all_text)
        if len(records) == 0:
            raise ValueError(
                "This does not appear to be an NMIMS SAP attendance report. "
                "Please upload a valid SVKM/NMIMS Student Attendance PDF."
            )
        metadata = _extract_metadata(page_texts[0], all_text)
        return metadata, records

    # Extract metadata from the first page
    metadata = _extract_metadata(page_texts[0], all_text)

    # Extract attendance records from all pages
    records = _extract_records(all_text)

    if len(records) == 0:
        raise ValueError(
            "No attendance records found in the PDF. "
            "The report may be empty, or the date range may have no records."
        )

    # Compute earliest and latest attendance record dates present in the report
    valid_dates = [r.date for r in records if r.date]
    if valid_dates:
        metadata.latest_record_date = max(valid_dates)
        metadata.earliest_record_date = min(valid_dates)

    return metadata, records


def _is_nmims_attendance_pdf(text: str) -> bool:
    """
    Check if the text content looks like an NMIMS attendance PDF.

    Requires only 1 of the 4 indicators because portal-fetched PDFs may omit
    the institution name text (rendered as image or absent from Chromium capture).
    Record-level validation is the real gatekeeper.
    """
    indicators = [
        "NMIMS" in text.upper() or "SVKM" in text.upper() or "MUKESH PATEL" in text.upper(),
        "Student Name" in text or "Student Number" in text or "Student No" in text,
        "Attendance" in text or "Attendance Report" in text,
        "Course Name" in text or "Sr" in text or "Sr No" in text,
    ]
    return sum(indicators) >= 1


def _check_file_type(data: bytes, filename: str) -> None:
    """
    Raise a descriptive ValueError if the bytes are obviously not a PDF.
    Detects HTML responses and common Microsoft Office formats.
    """
    if len(data) < 4:
        raise ValueError(f"The file '{filename}' appears to be empty or corrupt.")

    header = data[:8]

    # HTML response (common when portals return error pages instead of files)
    if header[:5] in (b'<!DOC', b'<html', b'<HTML') or data[:100].lower().startswith(b'<!doctype'):
        raise ValueError(
            "The portal returned an HTML page instead of a PDF. "
            "This usually means the session expired or the report generation failed. "
            "Please try again."
        )

    # Microsoft Office (OLE compound document: .xls, .doc, .ppt)
    if header[:8] == b'\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1':
        raise ValueError(
            f"The downloaded file '{filename}' is a Microsoft Office document, not a PDF. "
            "Please check the portal export settings."
        )

    # OOXML (.xlsx, .docx) — starts with PK (zip)
    if header[:2] == b'PK':
        raise ValueError(
            f"The downloaded file '{filename}' appears to be a ZIP/Office Open XML file (.xlsx/.docx). "
            "Please check the portal export settings."
        )

    # Must start with %PDF
    if not data[:5].startswith(b'%PDF'):
        raise ValueError(
            f"The file '{filename}' does not appear to be a valid PDF "
            f"(unexpected header: {data[:8]!r}). "
            "Please ensure you are uploading a PDF attendance report."
        )


def _extract_metadata(first_page_text: str, all_text: str) -> StudentMetadata:
    """Extract student metadata from the first page of the PDF."""
    lines = first_page_text.split('\n')
    lines = [l.strip() for l in lines if l.strip()]

    metadata = StudentMetadata(student_name="Unknown")

    # Parse student information from the header
    # The format in the PDF is label on one line, value before or after
    for i, line in enumerate(lines):
        # Student Name - the value appears BEFORE the label in the PDF text extraction
        if line == "Student Name" and i > 0:
            # Look backwards for the name (skipping institution lines)
            for j in range(i - 1, -1, -1):
                candidate = lines[j].strip()
                if candidate and candidate not in ["Student Name", "Student Number"] and \
                   "Page" not in candidate and "Mukesh" not in candidate and \
                   "SVKM" not in candidate and "NMIMS" not in candidate:
                    metadata.student_name = candidate
                    break

        elif line == "Student Number" and i > 0:
            for j in range(i - 1, -1, -1):
                candidate = lines[j].strip()
                if candidate and candidate != metadata.student_name and \
                   candidate not in ["Student Name", "Student Number"] and \
                   re.match(r'^\d+$', candidate):
                    metadata.student_number = candidate
                    break

        elif "Roll No" in line and i > 0:
            for j in range(i - 1, -1, -1):
                candidate = lines[j].strip()
                if candidate and re.match(r'^[A-Z]\d+', candidate):
                    metadata.roll_number = candidate
                    break

        elif "Academic Year" in line and "Academic Session" in line:
            # Value is on the line before
            for j in range(i - 1, -1, -1):
                candidate = lines[j].strip()
                if candidate and re.match(r'\d{4}', candidate):
                    metadata.academic_year = candidate
                    # Try to extract semester
                    sem_match = re.search(r'Semester\s+([IVXLC]+)', candidate)
                    if sem_match:
                        metadata.semester = sem_match.group(1)
                    break

        elif "Program Name" in line:
            for j in range(i - 1, -1, -1):
                candidate = lines[j].strip()
                if (
                    candidate
                    and candidate not in ["Program Name", "Student Name", "Student Number", "Roll No", "Roll No."]
                    and not re.match(r'^\d+$', candidate)
                ):
                    metadata.program = candidate
                    break

        elif "Attendance Report Duration" in line:
            duration_match = DURATION_PATTERN.search(first_page_text)
            if duration_match:
                metadata.report_start_date = duration_match.group(1)
                metadata.report_end_date = duration_match.group(2)

    # Extract institution from first few lines
    for line in lines[:5]:
        if "Mukesh Patel" in line or "NMIMS" in line or "SVKM" in line:
            metadata.institution = line
            break

    # Re-parse academic year and semester with a broader approach
    if not metadata.semester:
        sem_match = re.search(r'Semester\s+([IVXLC]+)', first_page_text)
        if sem_match:
            metadata.semester = sem_match.group(1)

    if not metadata.academic_year:
        year_match = re.search(r'(\d{4}-\d{4})', first_page_text)
        if year_match:
            metadata.academic_year = year_match.group(1)
        # Try with session info
        session_match = re.search(r'(\d{4}-\d{4},\s*Semester\s+[IVXLC]+)', first_page_text)
        if session_match:
            metadata.academic_year = session_match.group(1)

    return metadata


def _extract_records(all_text: str) -> list[AttendanceRecord]:
    """
    Extract attendance records from the full PDF text.

    The text extracted from the PDF has records in a predictable pattern:
    <serial_number>
    <course_name>
    <date>
    <start_time>
    <end_time>
    <status>

    Each record spans multiple lines in the extracted text.
    """
    lines = all_text.split('\n')
    lines = [l.strip() for l in lines]

    records = []
    i = 0

    while i < len(lines):
        # Look for a serial number (positive integer at start of a line)
        line = lines[i]

        # Skip header lines, page markers, etc.
        if not line or not re.match(r'^\d+$', line):
            i += 1
            continue

        sr_no = int(line)

        # Skip if this is a page number (e.g., "Page 1 of 11" produces "1")
        # Page numbers in the header are typically small and followed by specific patterns
        # Serial numbers should be sequential, and we can check context
        if sr_no == 0:
            i += 1
            continue

        # Try to parse the next lines as an attendance record
        record = _try_parse_record(lines, i, sr_no)
        if record:
            records.append(record)
            i += 6  # Skip past the lines we consumed
        else:
            i += 1

    return records


def _try_parse_record(lines: list[str], start_idx: int, sr_no: int) -> Optional[AttendanceRecord]:
    """
    Try to parse an attendance record starting at the given index.

    Expected pattern:
        lines[start_idx]:     serial number (already parsed)
        lines[start_idx + 1]: course name
        lines[start_idx + 2]: date (e.g., "Jul 13, 2026")
        lines[start_idx + 3]: start time (e.g., "11:00:01 AM")
        lines[start_idx + 4]: end time (e.g., "12:00:00 PM")
        lines[start_idx + 5]: status (P, A, NU, E, L)
    """
    # Make sure we have enough lines
    if start_idx + 5 >= len(lines):
        return None

    course_raw = lines[start_idx + 1].strip()
    date_str = lines[start_idx + 2].strip()
    start_time_str = lines[start_idx + 3].strip()
    end_time_str = lines[start_idx + 4].strip()
    status_str = lines[start_idx + 5].strip()

    # Validate date
    date_match = DATE_PATTERN.match(date_str)
    if not date_match:
        return None

    # Validate times
    start_time_match = TIME_PATTERN.match(start_time_str)
    end_time_match = TIME_PATTERN.match(end_time_str)
    if not start_time_match or not end_time_match:
        return None

    # Validate status
    if status_str not in VALID_STATUSES:
        return None

    # Parse date to ISO format
    month = MONTH_MAP[date_match.group(1)]
    day = int(date_match.group(2))
    year = int(date_match.group(3))
    iso_date = f"{year:04d}-{month:02d}-{day:02d}"

    # Parse times to 24-hour format
    start_time_24 = _convert_to_24h(start_time_match)
    end_time_24 = _convert_to_24h(end_time_match)

    # Normalize course name
    course_normalized = normalize_course_name(course_raw)

    return AttendanceRecord(
        serial_number=sr_no,
        course_raw=course_raw,
        course_normalized=course_normalized,
        date=iso_date,
        start_time=start_time_24,
        end_time=end_time_24,
        status=status_str,
    )


def _convert_to_24h(time_match: re.Match) -> str:
    """Convert a 12-hour time match to 24-hour format string HH:MM:SS."""
    hour = int(time_match.group(1))
    minute = int(time_match.group(2))
    second = int(time_match.group(3))
    period = time_match.group(4)

    if period == "AM":
        if hour == 12:
            hour = 0
    else:  # PM
        if hour != 12:
            hour += 12

    return f"{hour:02d}:{minute:02d}:{second:02d}"
